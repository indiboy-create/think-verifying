<?php

/*
|--------------------------------------------------------------------------
| think-verifying 验证码配置
|--------------------------------------------------------------------------
| 本组件只负责验证码的生成、缓存、token、场景隔离、频率限制与校验，
| 不包含短信或邮件发送实现。业务层拿到验证码后，可自行通过
| youvision/think-easysms、youvision/think-mailer 或其它通道发送。
*/

return [
    /*
    |--------------------------------------------------------------------------
    | 默认场景
    |--------------------------------------------------------------------------
    | 调用 generate() / check() / forget() 未显式指定场景时使用的场景名。
    | 场景用于隔离不同业务（注册、登录、找回密码等）的验证码与频率限制，
    | 同一 token 不能跨场景使用。
    */
    'default_scene' => 'default',

    /*
    |--------------------------------------------------------------------------
    | 缓存配置
    |--------------------------------------------------------------------------
    | 验证码、token、生成冷却与频率计数均保存在 ThinkPHP 缓存中。
    |
    | store  ：缓存驱动名，对应 config/cache.php 中 stores 下的键，null 表示默认驱动。
    |          多机部署时必须使用 redis / memcached 等共享缓存，不能使用 file 驱动，
    |          否则不同服务器之间无法共享验证码，校验会随机失败。
    | prefix ：所有缓存键的公共前缀，避免与业务缓存键冲突。
    */
    'cache' => [
        'store' => null,
        'prefix' => 'verifying',
    ],

    /*
    |--------------------------------------------------------------------------
    | 验证码签名密钥
    |--------------------------------------------------------------------------
    | 缓存中不保存明文验证码，而是保存 HMAC-SHA256 摘要，该值参与摘要计算。
    | 生产环境务必设置为随机长字符串；修改后已生成但尚未校验的验证码会全部失效。
    | 默认回退到环境变量 APP_KEY，便于直接复用项目密钥。
    */
    'secret' => verifying_env('VERIFYING_SECRET', verifying_env('APP_KEY', '')),

    /*
    |--------------------------------------------------------------------------
    | 验证码生成规则
    |--------------------------------------------------------------------------
    | length：验证码位数，建议 4~8 位。
    | type  ：验证码字符类型，可选：
    |         numeric - 纯数字（默认，最常用）
    |         nozero  - 纯数字且不含 0，避免用户把 0 与字母 O 混淆
    |         alpha   - 纯字母
    |         alnum   - 数字 + 字母
    */
    'code' => [
        'length' => (int) verifying_env('VERIFYING_CODE_LENGTH', 6),
        'type' => (string) verifying_env('VERIFYING_CODE_TYPE', 'numeric'),
    ],

    /*
    |--------------------------------------------------------------------------
    | 验证码有效期
    |--------------------------------------------------------------------------
    | 单位：秒。默认 300 秒（5 分钟）。到期后缓存自动失效，无法再通过校验。
    */
    'expire' => (int) verifying_env('VERIFYING_EXPIRE', 300),

    /*
    |--------------------------------------------------------------------------
    | 同账号生成冷却时间
    |--------------------------------------------------------------------------
    | 单位：秒。同一场景、同一手机号 / 邮箱生成成功后，需要等待该秒数才能再次生成。
    | 设为 0 表示关闭该限制。该限制只统计生成成功的请求。
    */
    'resend_interval' => (int) verifying_env('VERIFYING_RESEND_INTERVAL', 60),

    /*
    |--------------------------------------------------------------------------
    | 单个验证码允许的最大错误次数
    |--------------------------------------------------------------------------
    | 同一 token 连续输错达到该次数后，验证码立即作废，防止暴力枚举。
    | 设为 0 表示不限制错误次数（不推荐）。
    */
    'max_attempts' => (int) verifying_env('VERIFYING_MAX_ATTEMPTS', 5),

    /*
    |--------------------------------------------------------------------------
    | 生成频率限制
    |--------------------------------------------------------------------------
    | account_count / account_window：同一场景、同一手机号 / 邮箱在时间窗口内最多生成次数。
    | ip_count / ip_window          ：同一场景、同一 IP 在时间窗口内最多生成次数。
    |
    | window 单位为秒，count 设为 0 表示不限制。
    | 计数在生成请求时累加，生成失败的请求同样计入，用于防止恶意刷接口。
    */
    'limit' => [
        'account_count' => (int) verifying_env('VERIFYING_LIMIT_ACCOUNT_COUNT', 10),
        'account_window' => (int) verifying_env('VERIFYING_LIMIT_ACCOUNT_WINDOW', 3600),
        'ip_count' => (int) verifying_env('VERIFYING_LIMIT_IP_COUNT', 30),
        'ip_window' => (int) verifying_env('VERIFYING_LIMIT_IP_WINDOW', 3600),
    ],

    /*
    |--------------------------------------------------------------------------
    | 业务场景
    |--------------------------------------------------------------------------
    | 场景用于隔离验证码、冷却与错误次数。场景名可自由定义，未在 scenes 中
    | 出现的场景会直接使用全局配置。
    |
    | 每个场景可覆盖以下配置（未配置的项自动继承全局配置）：
    | expire          验证码有效期，单位秒
    | resend_interval 同账号生成冷却时间，单位秒
    | max_attempts    单个验证码允许的最大错误次数
    | code.length     验证码位数
    | code.type       验证码类型：numeric / nozero / alpha / alnum
    |
    | 示例：
    | 'register' => [
    |     'expire'          => 600,
    |     'resend_interval' => 120,
    |     'max_attempts'    => 3,
    |     'code'            => [
    |         'length' => 6,
    |         'type'   => 'numeric',
    |     ],
    | ],
    */
    'scenes' => [
        'default' => [],

        'register' => [
            // 注册场景可按需覆盖 expire / resend_interval / max_attempts / code
        ],

        'login' => [
            // 登录场景可按需覆盖 expire / resend_interval / max_attempts / code
        ],

        'reset_password' => [
            // 找回密码场景可按需覆盖 expire / resend_interval / max_attempts / code
        ],
    ],
];